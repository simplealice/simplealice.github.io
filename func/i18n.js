const supportedLanguages = ['en', 'ru', 'zh'];
const languageStorageKey = 'simplealice-language';
const i18nState = { lang: 'en' };

const translate = (key, vars) => {
    let value = (translations[i18nState.lang] && translations[i18nState.lang][key]);
    if (value === undefined) value = translations.en[key];
    if (value === undefined) return key;

    if (vars) {
        Object.keys(vars).forEach((name) => {
            value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), vars[name]);
        });
    }

    return value;
};

const updateLanguageButtons = () => {
    document.querySelectorAll('.lang-btn').forEach((button) => {
        const isActive = button.dataset.lang === i18nState.lang;
        button.classList.toggle('active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });
};

const applyTranslations = () => {
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        element.textContent = translate(element.dataset.i18n);
    });

    document.querySelectorAll('[data-i18n-html]').forEach((element) => {
        element.innerHTML = translate(element.dataset.i18nHtml);
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
        element.dataset.i18nAttr.split(';').forEach((pair) => {
            const separator = pair.indexOf(':');
            if (separator === -1) return;
            const attribute = pair.slice(0, separator).trim();
            const key = pair.slice(separator + 1).trim();
            if (attribute && key) element.setAttribute(attribute, translate(key));
        });
    });

    document.documentElement.lang = i18nState.lang === 'zh' ? 'zh-CN' : i18nState.lang;
    document.title = translate('meta.title');

    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute('content', translate('meta.description'));

    updateLanguageButtons();
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: i18nState.lang } }));
};

const setLanguage = (lang, options = {}) => {
    i18nState.lang = translations[lang] ? lang : 'en';

    try {
        localStorage.setItem(languageStorageKey, i18nState.lang);
    } catch (error) {
        // Storage can be unavailable in private mode.
    }

    applyTranslations();

    if (options.updateUrl !== false) {
        try {
            const url = new URL(window.location.href);
            if (i18nState.lang === 'en') {
                url.searchParams.delete('lang');
            } else {
                url.searchParams.set('lang', i18nState.lang);
            }
            window.history.replaceState(window.history.state, '', url.pathname + url.search + url.hash);
        } catch (error) {
            // Ignore URL updates if the History API is unavailable.
        }
    }
};

const detectLanguage = () => {
    try {
        const requested = new URLSearchParams(window.location.search).get('lang');
        if (requested && translations[requested.toLowerCase()]) return requested.toLowerCase();
    } catch (error) {
        // Ignore malformed URLs.
    }

    try {
        const stored = localStorage.getItem(languageStorageKey);
        if (stored && translations[stored]) return stored;
    } catch (error) {
        // Storage can be unavailable in private mode.
    }

    const browserLanguage = (navigator.language || 'en').toLowerCase();
    if (browserLanguage.startsWith('ru')) return 'ru';
    if (browserLanguage.startsWith('zh')) return 'zh';
    return 'en';
};

document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

window.i18n = {
    t: translate,
    setLanguage,
    applyTranslations,
    get lang() {
        return i18nState.lang;
    }
};

setLanguage(detectLanguage(), { updateUrl: false });
